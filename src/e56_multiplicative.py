"""E56: R for multiplicatively self-similar sets (candidates suggested by the SR picture: front-loaded at every scale,
closed under dilation by small primes, positive spikes at smooth rationals).
  smooth(X, y)      = {2 <= a <= X : P+(a) <= y}          (y-smooth; A ∩ pZ = p·smooth(X/p, y) for p <= y)
  smooth_odd(X, y)  = odd y-smooth numbers
  rough(X, y)       = {a <= X : P-(a) > y}                 (complement-type control)
  mult_closed(X, gens) = multiplicative semigroup generated by gens, <= X
M by 16x oversampled FFT grid + local refinement (UNCERTIFIED; ratio diagnostic).
Usage: python src/e56_multiplicative.py > examples/e56/e56.jsonl
"""
import json, math, sys
import numpy as np
from scipy.optimize import minimize_scalar

def lpf_table(X):
    lp = np.arange(X + 1); sp = np.zeros(X + 1, dtype=np.int64)
    for p in range(2, X + 1):
        if sp[p] == 0:
            sp[p::p] = np.where(sp[p::p] == 0, p, sp[p::p])
    big = np.ones(X + 1, dtype=np.int64)
    for a in range(2, X + 1):
        big[a] = max(sp[a], big[a // sp[a]])
    return sp, big          # smallest and largest prime factor

def Mval(A):
    A = np.asarray(A, dtype=np.int64); X = int(A.max())
    G = 16 << math.ceil(math.log2(X)); c = np.zeros(G); np.add.at(c, A, 1.0)
    f = np.fft.fft(c).real; j = int(np.argmin(f)); x0 = 2 * math.pi * j / G
    h = lambda x: float(np.cos(A * x).sum())
    r = minimize_scalar(h, bounds=(x0 - 2 * math.pi / G, x0 + 2 * math.pi / G), method="bounded", options={"xatol": 1e-12})
    return -min(f.min(), r.fun), r.x if r.fun < f.min() else x0

def report(name, A, out, **kw):
    A = sorted(set(A)); n = len(A)
    if n < 10: return
    M, x = Mval(A); t = x / (2 * math.pi) % 1
    from fractions import Fraction
    fr = Fraction(t).limit_denominator(200)
    print(json.dumps(dict(set=name, n=n, X=max(A), R=round(M / math.sqrt(n), 4), M=round(M, 3),
                          xmin_over_2pi=round(t, 6), near=f"{fr.numerator}/{fr.denominator}", **kw)), file=out, flush=True)

if __name__ == "__main__":
    Xmax = 2 ** 18
    sp, big = lpf_table(Xmax)
    for X in (2 ** 12, 2 ** 14, 2 ** 16, 2 ** 18):
        idx = np.arange(2, X + 1)
        for y in (3, 5, 7, 11, 13, 19, 31, 61, 127):
            A = idx[big[2:X + 1] <= y].tolist()
            report(f"smooth_y{y}", A, sys.stdout, y=y)
            report(f"smooth_odd_y{y}", [a for a in A if a % 2], sys.stdout, y=y)
        for u in (2.0, 3.0):
            y = int(round(X ** (1 / u)))
            A = idx[big[2:X + 1] <= y].tolist()
            report(f"smooth_u{u:g}", A, sys.stdout, y=y)
            report(f"rough_y{y}", idx[sp[2:X + 1] > y].tolist(), sys.stdout, y=y)
